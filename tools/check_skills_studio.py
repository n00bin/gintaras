class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*a):pass

FAST_AUDIO="""(()=>{const NativeAudio=window.Audio;window.__completedMedia=[];window.Audio=function(url){const audio=new NativeAudio(url);audio.defaultPlaybackRate=8;audio.playbackRate=8;audio.addEventListener('loadedmetadata',()=>audio.playbackRate=8);audio.addEventListener('ended',()=>window.__completedMedia.push({url:String(url),duration:audio.duration,time:audio.currentTime}));return audio;};window.Audio.prototype=NativeAudio.prototype;})();"""

def source_expression_study(page,d,unit_id):
    entries=page.evaluate('id=>WordamiSourceSupport.units[id]',unit_id)
    d.get_by_role('button',name='Practise source expressions',exact=True).click()
    for entry in entries:
        d.get_by_role('button',name='Practise this expression',exact=True).click()
        d.get_by_role('button',name=entry['meaning'],exact=True).click()
        d.get_by_role('button',name='Next expression',exact=True).click()
    assert 'source expressions checked' in d.inner_text()
    d.get_by_role('button',name='Return to source study',exact=True).click()

def grammar_lesson(page,d,band):
    d.get_by_role('button',name='Learn grammar',exact=True).click()
    g=page.locator('#a1-practice')
    assert not page.evaluate("id=>WordamiActivities.begin('grammar.'+id)",band)
    lesson=page.evaluate('id=>WordamiGrammarContent.lessons.find(l=>l.id===id)',band)
    g.get_by_role('button',name='I have studied the examples',exact=True).click()
    for index,t in enumerate(lesson['tasks']):
        if t['kind']=='choice':
            if band=='A1' and index==0:
                g.get_by_role('button',name=t['options'][(t['answer']+1)%3],exact=True).click()
                assert 'try again' in g.locator('[role=status]').inner_text()
            g.get_by_role('button',name=t['options'][t['answer']],exact=True).click()
        else:
            g.get_by_role('textbox',name='Your learned sentence').fill(t['accept'][0])
            g.get_by_role('button',name='Check sentence',exact=True).click()
        g.get_by_role('button',name='Continue',exact=True).click()
    assert page.evaluate('id=>WordamiGrammar.ready(id)',band)
    g.get_by_role('button',name='Back to unit',exact=True).click()

def vocabulary_lesson(page,d,unit_id):
    entries=page.evaluate('id=>WordamiVocabularyContent.units[id]',unit_id)
    for index,word in enumerate(entries):
        d.get_by_role('button',name='Practise this word',exact=True).click()
        assert d.locator('p:not(.skills-text)').filter(has_text=re.compile('^'+re.escape(word['meaning'])+'$')).is_hidden()
        if index==0:
            d.get_by_role('button',name=entries[3]['meaning'],exact=True).click()
            assert 'try again' in d.locator('[role=status]').inner_text()
        d.get_by_role('button',name=word['meaning'],exact=True).click()

def answer_check(page,d,level,kind,wrong=False):
    title='Read and understand' if kind=='reading' else 'Listen and understand'
    d.get_by_role('button',name=re.compile('(?:Begin|Review).*'+title)).click()
    questions=level['readingQuestions'] if kind=='reading' else level['questions']
    for index,q in enumerate(questions):
        if kind=='listening' and index==0:
            assert d.get_by_role('button',name=q[1][q[2]],exact=True).is_disabled()
            d.get_by_role('button',name='Listen to the full recording').click()
            d.get_by_role('button',name=q[1][q[2]],exact=True).wait_for(state='visible')
            page.wait_for_function("document.querySelector('#skills-studio [role=status]').textContent.includes('Recording finished')",timeout=25000)
        chosen=(q[2]+1)%3 if wrong and index==0 else q[2]
        d.get_by_role('button',name=q[1][chosen],exact=True).click()
        if index<2:assert 'Comprehension feedback' not in d.inner_text()
    assert ('2 of 3 correct' if wrong else '3 of 3 correct') in d.inner_text()
    d.get_by_role('button',name='Back to stage',exact=True).click()

def record_response(page,d,quota=False,retain=False):
    start=d.get_by_role('button',name='Start recording',exact=True)
    start.click()
    d.get_by_role('button',name='Stop recording',exact=True).wait_for()
    page.wait_for_timeout(1200)
    d.get_by_role('button',name='Stop recording',exact=True).click()
    page.wait_for_function("[...document.querySelectorAll('#skills-studio button')].some(b=>b.textContent==='Replay my response'&&!b.disabled)")
    assert d.get_by_role('button',name='Save self-review',exact=True).is_disabled()
    d.get_by_role('button',name='Replay my response',exact=True).click()
    page.wait_for_function("[...document.querySelectorAll('#skills-studio button')].some(b=>b.textContent==='Save self-review'&&!b.disabled)")
    if retain:
        d.get_by_role('button',name='Save a portfolio copy',exact=True).click()
        d.locator('[role=status]').filter(has_text='Recording copy saved').wait_for()
    d.get_by_role('button',name='Save self-review',exact=True).click()
    assert 'Review all three criteria' in d.locator('[role=status]').inner_text()
    for box in d.get_by_role('checkbox').all():box.check()
    revision=d.locator('#production-revision').count()>0
    d.get_by_role('textbox',name='Your speaking reflection').fill('I made the link between the reason and recommendation more explicit in the second take.' if revision else 'I will make the connection between my reason and recommendation clearer.')
    if quota:
        page.evaluate("()=>{window.__nativeSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k.startsWith('wordami.skills.v1.'))throw new DOMException('test full','QuotaExceededError');return __nativeSetItem.call(this,k,v);};}")
        d.get_by_role('button',name='Save self-review',exact=True).click()
        assert 'could not be saved' in d.locator('[role=status]').inner_text()
        assert not page.evaluate('WordamiSkillsStudio.catalogue()[0].spoken.production')
        page.evaluate('()=>{Storage.prototype.setItem=window.__nativeSetItem;}')
    d.get_by_role('button',name='Save self-review',exact=True).click()
    if d.locator('#production-revision').count() and not revision:record_response(page,d,retain=retain)

def writing_projects(page,lang,level):
    if level.get('project'):
        d=page.locator('#skills-studio')
        d.get_by_role('button',name='Open writing assignment',exact=True).click()
        original=level['reading']+'\n\n'+level['writing']['phrases'][0][0]
        d.locator('#skills-draft').fill(original)
        d.get_by_role('button',name='Back to stage',exact=True).click()
        d.get_by_role('button',name='Open writing assignment',exact=True).click()
        assert d.locator('#skills-draft').input_value()==original
        d.get_by_role('button',name='Get revision guidance',exact=True).click()
        d.get_by_role('button',name='Save revised assignment',exact=True).click()
        assert 'Revise the draft' in d.locator('[role=status]').inner_text()
        d.locator('#skills-draft').fill(original+'\n\n'+level['writing']['phrases'][1][0])
        for i in range(3):d.get_by_role('textbox',name='Writing evidence '+str(i+1)).fill(level['writing']['phrases'][0][0])
        d.get_by_role('textbox',name='Your writing revision reflection').fill('I clarified the order and added a more precise practical detail.')
        if level['id']=='A1-shopping':
            page.evaluate("()=>{window.__nativeSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k.startsWith('wordami.skills.v1.'))throw new DOMException('test full','QuotaExceededError');return __nativeSetItem.call(this,k,v);};}")
            d.get_by_role('button',name='Save revised assignment',exact=True).click()
            assert 'could not be saved' in d.locator('[role=status]').inner_text()
            assert not page.evaluate("WordamiSkillsStudio.catalogue().find(l=>l.id==='A1-shopping').complete")
            page.evaluate('()=>{Storage.prototype.setItem=window.__nativeSetItem;}')
        d.get_by_role('button',name='Save revised assignment',exact=True).click()
        assert 'Assignment revised and self-reviewed' in d.inner_text()
        d.get_by_role('button',name='Back to stage',exact=True).click()
        return
    id=level['id'];page.goto(BASE+f'?preview=1&lang={lang}#writing-{id}')
    d=page.locator('#writing-studio')
    d.get_by_role('button',name='Begin language preparation').click()
    for phrase in level['writing']['phrases']:
        d.get_by_role('button',name='Practise this phrase').click()
        d.get_by_role('button',name=phrase[1],exact=True).click()
    for _,answers,correct in level['writing']['questions']:
        d.get_by_role('button',name=answers[correct],exact=True).click()
    d.get_by_role('button',name='Begin writing projects').click()
    for index in range(3):
        d.get_by_role('button',name='Start project',exact=True).first.click()
        original=level['writing']['model']+'\n\n'+level['writing']['phrases'][0][0]
        d.locator('#ws-draft').fill(original)
        d.get_by_role('button',name='Get revision guidance').click()
        d.locator('#ws-draft').fill(original+'\n\n'+level['writing']['phrases'][1][0])
        for i in range(4):d.get_by_role('textbox',name='Evidence for criterion '+str(i+1)).fill(level['writing']['phrases'][0][0])
        d.locator('#ws-reflection').fill('I clarified the structure and added a more specific final point.')
        d.get_by_role('button',name='Save revised project').click()
        assert 'Project revised and self-reviewed' in d.inner_text()
        if index<2:d.get_by_role('button',name='Continue the writing pathway').click()
    d.get_by_role('button',name='Continue all skills',exact=True).click()

def main():
    global BASE
    OUT.mkdir(parents=True,exist_ok=True)
    server=http.server.ThreadingHTTPServer(('127.0.0.1',0),partial(Quiet,directory=str(ROOT)))
    threading.Thread(target=server.serve_forever,daemon=True).start();BASE=f'http://127.0.0.1:{server.server_port}/'
    reports=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(channel='chrome',headless=True,args=['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream'])
        for lang in ['lt','es']:
            context=browser.new_context(viewport={'width':390,'height':844},accept_downloads=True,permissions=['microphone'])
            context.add_init_script(FAST_AUDIO)
            page=context.new_page();page.set_default_timeout(15000);errors=[]
            page.on('pageerror',lambda e:errors.append(str(e)))
            page.goto(BASE+f'?preview=1&lang={lang}#skills-C2');page.wait_for_function('window.WordamiCoursePath');page.locator('#splash').wait_for(state='detached')
            page.evaluate(FOUNDATIONS_SEED)
            d=page.locator('#skills-studio')
            assert 'Complete the preceding unit' in d.inner_text()
            assert not page.evaluate("WordamiActivities.begin('skills.C2.reading')")
            assert not page.evaluate("WordamiSkillsStudio.catalogue().find(l=>l.id==='C2').prepared")
            page.evaluate("()=>{S.welcomed=true;S.toured=true;S.meAsked=1;S.signinAsked='test';S.seenVersion=APP_VERSION;S.sound=false;save();}")
            baseline=page.evaluate('JSON.stringify(S)')
            levels=page.evaluate('WordamiSkillsContent.units||WordamiSkillsContent.levels')
            for level_index,level in enumerate(levels):
                page.goto(BASE+f'?preview=1&lang={lang}#skills-'+level['id'])
                assert d.get_by_role('button',name=re.compile('Begin.*Read and understand')).is_disabled()
                d.get_by_role('button',name='Learn the language',exact=True).click()
                vocabulary_lesson(page,d,level['id'])
                for phrase in level['writing']['phrases']:
                    d.get_by_role('button',name='Practise this meaning').click()
                    d.get_by_role('button',name=phrase[1],exact=True).click()
                d.get_by_role('button',name='Finish source preparation',exact=True).click()
                assert 'confirm before continuing' in d.locator('[role=status]').inner_text()
                if (level.get('band') or level['id']) in ['B1','B2','C1','C2']:source_expression_study(page,d,level['id'])
                d.get_by_role('checkbox').check()
                d.get_by_role('button',name='Finish source preparation',exact=True).click()
                if d.get_by_role('button',name='Learn grammar',exact=True).count():
                    assert d.get_by_role('button',name=re.compile('Begin.*Read and understand')).is_disabled()
                    grammar_lesson(page,d,level.get('band',level['id']))
                if level_index==0:
                    answer_check(page,d,level,'reading',wrong=True)
                    assert d.get_by_role('button',name='Begin production',exact=True).is_disabled()
                    d.get_by_role('button',name=re.compile('Begin.*Read and understand')).click()
                    d.get_by_role('button',name='Try a fresh check',exact=True).click()
                    for q in level['readingQuestions']:d.get_by_role('button',name=q[1][q[2]],exact=True).click()
                    d.get_by_role('button',name='Back to stage',exact=True).click()
                else:answer_check(page,d,level,'reading')
                answer_check(page,d,level,'listening')
                d.get_by_role('button',name='Begin production',exact=True).click()
                record_response(page,d,quota=level_index==0)
                d.get_by_role('button',name='Begin interaction',exact=True).click()
                for turn in range(3):
                    assert d.get_by_role('button',name='Start recording',exact=True).is_disabled()
                    d.get_by_role('button',name='Hear your partner',exact=True).click()
                    page.wait_for_function("[...document.querySelectorAll('#skills-studio button')].some(b=>b.textContent==='Start recording'&&!b.disabled)")
                    record_response(page,d)
                d.get_by_role('button',name='Begin mediation',exact=True).click()
                record_response(page,d)
                assert not page.evaluate('id=>WordamiSkillsStudio.catalogue().find(l=>l.id===id).complete',level['id'])
                writing_projects(page,lang,level)
                assert not page.evaluate('id=>WordamiSkillsStudio.progress(id).complete',level['id'])
                required_applications(page,level['id'])
                written_exchanges(page,level['id'])
                practical_forms(page,level['id'])
                practical_tables(page,level['id'])
                extended_reading(page,level['id'])
                assert page.evaluate('id=>WordamiSkillsStudio.catalogue().find(l=>l.id===id).complete',level['id'])
                assert page.evaluate('JSON.stringify(S)')==baseline
                assert all(s['level'] is None for s in page.evaluate('WordamiActivities.summary()'))
                assert 'recommendation clearer' not in page.evaluate("localStorage.getItem('wordami.activities.v1.'+LANG.code)")
                if level['id']=='C2':
                    page.set_viewport_size({'width':320,'height':740});assert d.evaluate('(e)=>e.scrollWidth<=e.clientWidth')
                    page.screenshot(path=str(OUT/(lang+'-c2-mobile.png')))
                print(lang+' '+level['id']+' all skills and writing passed',flush=True)
                (OUT/(lang+'-walkthrough-checkpoint.json')).write_text(json.dumps({'scope':'Synthetic browser workflow fixtures, not learner data','lastPassedUnit':level['id'],'unitsPassed':level_index+1,'baseline':baseline,'localStorage':page.evaluate('Object.fromEntries(Object.keys(localStorage).map(k=>[k,localStorage.getItem(k)]))')},ensure_ascii=False),encoding='utf8')
            assert all(l['complete'] for l in page.evaluate('WordamiSkillsStudio.catalogue()'))
            assert all(l['complete'] for l in page.evaluate('WordamiGrammar.catalogue()'))
            assert page.evaluate('WordamiStudyMemory.summary().learned')==page.evaluate('WordamiVocabularyContent.deck().length')
            page.evaluate("navigator.serviceWorker.ready.then(()=>new Promise(resolve=>{if(navigator.serviceWorker.controller)resolve();else navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true})}))")
            context.set_offline(True);page.reload()
            assert all(l['complete'] for l in page.evaluate('WordamiSkillsStudio.catalogue()'))
            context.set_offline(False)
            d.get_by_role('button',name='All skill stages',exact=True).click()
            with page.expect_download() as info:d.get_by_role('button',name='Export skills portfolio').click()
            exported=json.loads(Path(info.value.path()).read_text(encoding='utf8'));assert len(exported['levels'])==len(levels)
            assert not errors,errors
            reports.append({'language':lang,'completeUnits':len(levels),'writingProjects':sum(1 if l.get('project') else 3 for l in levels),'comprehensionQuestions':6*len(levels),'spokenResponses':5*len(levels),'vocabularyEntriesStudied':8*len(levels),'reviewCards':page.evaluate('WordamiStudyMemory.summary().learned'),'pageErrors':errors,'courseStateUnchanged':True})
            context.close()
        public=browser.new_page();public.goto(BASE+'?preview=0&lang=lt#skills');assert public.locator('#skills-studio').count()==0
        browser.close()
    server.shutdown();(OUT/'verification.json').write_text(json.dumps({'passed':True,'languages':reports},indent=2),encoding='utf8')
    print('All course units and writing projects passed vocabulary, grammar, real playback, recording, revision, unlock, export and offline checks.')

if __name__=='__main__':main()
